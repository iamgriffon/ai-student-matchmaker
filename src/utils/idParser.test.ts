import { describe, expect, test } from "bun:test";
import { parseId } from "./idParser.ts";

const UUID_V4 = "abcdef01-1234-4000-8000-000000000001";
const UUID_V7 = "01a1242e-ae78-75c9-a4c9-dfafa6488b9b";
const EXPECTED_ID_LENGTH = 36;

describe("parseId", () => {
  test("accepts a UUID v4 and preserves its string value", () => {
    expect(parseId(UUID_V4)).toBe(UUID_V4);
    expect(parseId(UUID_V4)).toHaveLength(EXPECTED_ID_LENGTH);
  });

  test("accepts the UUID v7 format generated by the database", () => {
    expect(parseId(UUID_V7)).toBe(UUID_V7);
  });

  test("normalizes uppercase hexadecimal characters", () => {
    expect(parseId(UUID_V4.toUpperCase())).toBe(UUID_V4);
  });

  test("trims surrounding whitespace", () => {
    expect(parseId(` \n${UUID_V7}\t `)).toBe(UUID_V7);
  });

  for (const [label, value] of [
    ["empty value", ""],
    ["whitespace only", "   "],
    ["arbitrary text", "missing-user"],
    ["missing hyphens", UUID_V4.replaceAll("-", "")],
    ["invalid hexadecimal character", UUID_V4.replace("a", "g")],
    ["short UUID", UUID_V4.slice(1)],
    ["trailing characters", `${UUID_V4}extra`],
    ["internal whitespace", UUID_V4.replace("-", " -")],
    ["invalid UUID variant", "abcdef01-1234-4000-7000-000000000001"],
  ] as const) {
    test(`rejects ${label}`, () => {
      expect(() => parseId(value)).toThrow();
    });
  }
});
